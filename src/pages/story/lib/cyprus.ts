const LON0 = 32.25;
const LAT0 = 35.72;
/** Единиц карты на градус широты; долгота сжата на cos(35°). */
const K = 974;
const LON_K = K * Math.cos((35 * Math.PI) / 180);

/** Точка карты → долгота, широта (для сборки карты высот, scripts/build-heightmap.ts). */
export const ungeo = (x: number, y: number): [number, number] => [LON0 + (x - 60) / LON_K, LAT0 - (y - 75) / K];

/** Долгота, широта → точка карты. */
export const geo = (lon: number, lat: number): [number, number] => [
  Math.round(60 + (lon - LON0) * LON_K),
  Math.round(75 + (LAT0 - lat) * K),
];

