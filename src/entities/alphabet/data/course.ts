// ---------- задания из слов ----------

const bare = (s: string) => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();

function distance(a: string, b: string): number {
  const row = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    let prev = row[0]!;
    row[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const tmp = row[j]!;
      row[j] = Math.min(row[j]! + 1, row[j - 1]! + 1, prev + (a[i - 1] === b[j - 1] ? 0 : 1));
      prev = tmp;
    }
  }
  return row[b.length]!;
}

/** Три самых похожих по написанию слова — неверные варианты (похожие путать интереснее). */
function nearest(word: ReadingExample, pool: readonly ReadingExample[]): ReadingExample[] {
  return pool
    .filter((o) => bare(o.greek) !== bare(word.greek))
    .map((o) => ({ o, d: distance(bare(word.greek), bare(o.greek)) }))
    .toSorted((a, b) => a.d - b.d)
    .slice(0, 3)
    .map((x) => x.o);
}

/** «Услышь и выбери»: звучит слово — выбрать, как оно пишется. */
function listenItems(words: readonly ReadingExample[], pool = words): QuizItem[] {
  return words.map((x) => ({
    prompt: x.greek,
    speak: x.greek,
    answer: x.greek,
    distractors: nearest(x, pool).map((o) => o.greek),
    note: `${x.reading} — ${x.russian}`,
  }));
}

/** «Как читается»: слово — выбрать чтение. */
function readItems(words: readonly ReadingExample[], pool = words): QuizItem[] {
  return words.map((x) => ({
    prompt: x.greek,
    answer: x.reading,
    distractors: nearest(x, pool).map((o) => o.reading),
    note: x.russian,
  }));
}

