/**
 * Что отдать синтезатору вместо слога. Короткие слоги он иногда читает не как слог:
 * по буквам (μι — «μι-γιώτα», τί — «ταυ-ι») или как сокращение (κα — «κυρία»).
 * Для таких слогов — подобранное написание с тем же звуком (ударение или другая буква «и»).
 * Подбор — по длине звука в mp3: слог по буквам звучит в 2–3 раза дольше. Проверено на слух не всё.
 * Добавили слог в курс — прослушайте; если читается странно, допишите сюда.
 */
const SPEECH: Record<string, string> = {
  μι: 'μί',
  κα: 'κά',
  ρι: 'ροί',
  δι: 'δί',
  γι: 'γή',
};

export const syllableSpeech = (greek: string): string => SPEECH[greek] ?? greek;
