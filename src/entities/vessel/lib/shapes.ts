/**
 * Ручка: точки [радиус, высота, сдвиг вбок], `u` — где на окружности (0 — сзади, 0.25 и 0.75 — по бокам, 0.5 — спереди).
 * Роспись: панно спереди — центр холста, сзади — края холста.
 */
export interface Handle {
  u: number;
  pts: readonly (readonly [number, number, number?])[];
}

export interface ShapeDef {
  /** Профиль снизу вверх: [радиус, высота]; последняя точка — внутренний край горла. */
  profile: readonly (readonly [number, number])[];
  handles: readonly Handle[];
  /** Толщина ручки. */
  thick?: number;
}

const sides = (pts: Handle['pts']): Handle[] => [
  { u: 0.25, pts },
  { u: 0.75, pts },
];
/** Горизонтальная ручка-петля на тулове (гидрия): от тулова наружу и обратно, вбок по окружности. */
const loop = (r: number, y: number, out = 0.18, half = 0.15): Handle['pts'] => [
  [r, y, -half],
  [r + out, y + 0.04, -half * 0.6],
  [r + out, y + 0.04, half * 0.6],
  [r, y, half],
];

