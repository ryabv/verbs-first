/** Высота сосуда на постаменте и предельный радиус (в мире сцены). */
export const FIT_H = 2.1;
export const FIT_R = 0.95;

/** Портрет для полки (`pnpm museum:bake`): кадр в пикселях, пикселей на единицу мира, нижний край кадра в мире. */
export const PORTRAIT_W = 240;
export const PORTRAIT_H = 300;
export const PX = 112;
export const FLOOR = -0.12;

/** Где в кадре портрета сосуд по высоте: доли кадра снизу (низ и верх) — чтобы заливать силуэт по самому сосуду. */
export function portraitSpan(shape: VesselShape): { bottom: number; top: number } {
  const def = SHAPES[shape];
  const maxY = Math.max(...def.profile.map(([, y]) => y));
  const maxR = Math.max(...def.profile.map(([r]) => r), ...def.handles.flatMap((h) => h.pts.map((q) => q[0])));
  const height = maxY * Math.min(FIT_H / maxY, FIT_R / maxR);
  const frame = PORTRAIT_H / PX;
  return { bottom: -FLOOR / frame, top: (height - FLOOR) / frame };
}
