const monthNo = (month: string) => {
  const [y, m] = month.split('-').map(Number) as [number, number];
  return y * 12 + m - 1;
};

/**
 * Сосуд месяца: у каждого сосуда свой месяц (`month`). Месяцы вне каталога (после последнего, демо до запуска) —
 * по кругу от первого; черепки для них режутся на странице.
 */
export function vesselOfMonth(month: string): Vessel {
  const own = VESSELS.find((v) => v.month === month);
  if (own) return own;
  const i = monthNo(month) - monthNo(VESSELS[0]!.month);
  return VESSELS[((i % VESSELS.length) + VESSELS.length) % VESSELS.length]!;
}
