import { stripAccents } from '@/shared/lib/greek';

/**
 * Служебные слова: артикли, предлоги, союзы, частицы, краткие местоимения. По переводу их не узнать
 * (για — «для», με — «с»), поэтому — списком. В «что значит слово», в вариантах ответа и в карточках из ошибок
 * их не спрашиваем: смысл у них — в конструкции, а не сам по себе.
 */
const SERVICE = new Set(
  [
    'ο', 'η', 'το', 'οι', 'τα', 'τον', 'την', 'των', 'ο/η/το', 'ένας/μία/ένα',
    'σε', 'με', 'για', 'από', 'χωρίς', 'παρά', 'μέχρι', 'ως', 'προς', 'κατά',
    'και', 'ή', 'αλλά', 'όμως', 'ότι', 'όταν', 'αν', 'επειδή', 'ούτε',
    'θα', 'να', 'δεν', 'μην', 'μη', 'ας', 'πιο',
    'μου', 'σου', 'του', 'της', 'μας', 'σας', 'τους',
  ].map((w) => stripAccents(w)),
);

const LABEL = /артикль|предлог|частица|союз/;

/** Служебное слово — по словарной форме (и по пометке в переводе, если она есть). */
export function isServiceWord(entry: { greek: string; russian: string }): boolean {
  return SERVICE.has(stripAccents(entry.greek.toLowerCase())) || LABEL.test(entry.russian);
}
