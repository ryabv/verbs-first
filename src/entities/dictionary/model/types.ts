/**
 * Почему форма написана именно так: короткое пояснение и правило справочника
 * («тема#правило», страница /grammar/<тема>#<правило>). Греческие куски в пояснении — в `обратных кавычках`.
 */
export interface FormNote {
  note: string;
  rule: `${string}#${string}`;
}

/**
 * Слово общего словаря: словарная форма (существительное — с артиклем), перевод
 * и формы, в которых оно встречается в текстах сайта. Формы пишутся явно — не генерируем правилами.
 */
export interface DictEntry {
  greek: string;
  russian: string;
  forms?: string[];
  /** «Почему так?» для форм (ключ — форма как в forms; можно и словарную, если слово многозначно). */
  why?: Record<string, FormNote>;
}
